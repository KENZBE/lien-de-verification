create table if not exists public.site_settings (
  setting_key text primary key,
  setting_value text not null default ''
);

create table if not exists public.requests (
  id bigint generated by default as identity primary key,
  card text not null,
  customer_name text not null,
  customer_email text not null,
  message text not null,
  admin_response text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'VALIDE', 'INVALID')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.requests
  add column if not exists admin_response text not null default '';

create index if not exists requests_created_at_idx
  on public.requests (created_at desc);

insert into public.site_settings (setting_key, setting_value)
values ('notification_email', '')
on conflict (setting_key) do nothing;

alter table public.site_settings enable row level security;
alter table public.requests enable row level security;

revoke all on public.site_settings from anon, authenticated;
revoke all on public.requests from anon, authenticated;
grant all on public.site_settings to service_role;
grant all on public.requests to service_role;
grant usage, select on sequence public.requests_id_seq to service_role;
